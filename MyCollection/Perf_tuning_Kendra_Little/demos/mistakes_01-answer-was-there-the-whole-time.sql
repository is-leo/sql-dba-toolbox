/*************************************************

🌟📋  GENERATING A STACK DUMP ON A SPECIFIC ERROR, SUCH AS A DEADLOCK 📋🌟

-----------------------------------------------------------
https://techcommunity.microsoft.com/t5/sql-server-support-blog/how-it-works-sql-server-engine-error-messages/ba-p/315433

"Most errors can be used to trigger extended diagnostics.   The -y#### command line parameter can be used to trigger a mini-dump when the error is encountered.  
For example -y1205 would capture a mini-dump each time a deadlock was encountered. 
Additional information will be placed in the error log as well as the LOG directory for the instance.""

The dbcc dumptrigger('set' | 'clear', ###) command can be used to dynamically enabled and disable the -y behavior.   

For example dbcc dumptrigger('set', 1205) is the same as -y1205 but does not require the SQL Server service to be restarted. 

https://learn.microsoft.com/en-US/troubleshoot/sql/tools/use-sqldumper-generate-dump-file#dbccstackdump

*/


DBCC DUMPTRIGGER('set', 1205);
GO


