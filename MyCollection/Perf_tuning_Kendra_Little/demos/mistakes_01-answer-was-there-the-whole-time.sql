/* It can be convenient and sometimes safer to persist deadlock data to a separate trace that uses a file 
for longer term storage, if we don't have this being picked up by a monitoring system.

There is slightly different syntax and considerations for Azure SQL Database:
    https://learn.microsoft.com/en-us/azure/azure-sql/database/analyze-prevent-deadlocks?view=azuresql&tabs=ring-buffer
    Essentially, use sqlserver.database_xml_deadlock_report and create the session ON DATABASE
        instead of sqlserver.xml_deadlock_report and creating the session ON SERVER
*/

CREATE EVENT SESSION [Deadlocks] ON SERVER 
ADD EVENT sqlserver.xml_deadlock_report
ADD TARGET package0.event_file(SET filename=N'/var/opt/mssql/log/Deadlocks.xel')
WITH (STARTUP_STATE=ON, MAX_MEMORY=4 MB)
GO

ALTER EVENT SESSION [Deadlocks] ON SERVER
    STATE = START;
GO

/* Reproduce the deadlock using the code above */

ALTER EVENT SESSION [Deadlocks] ON SERVER
    STATE = STOP;
GO

DROP EVENT SESSION Deadlocks ON SERVER;
GO

