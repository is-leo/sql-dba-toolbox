🌟📋 STACK DUMPS 📋🌟

I'm a huge believer in being able to reproduce issues outside of production whenever we can.
This can help ensure that we are familiar with how things will look, as well as test monitoring
systems to ensure they pick up on these problems.

Let's cause a stack dump generated by a specific error. 
We'll use a deadlock because it's easy to generate, but you wouldn't want to do this in production.

-----------------------------------------------------------

https://learn.microsoft.com/en-US/troubleshoot/sql/tools/use-sqldumper-generate-dump-file#dbccstackdump

"The DBCC STACKDUMP command can help you create a memory dump in the LOG directory of your SQL Server instance installation. 
The command will by default create a minidump with all threads, which has limited size and is adequate to reflect the state 
of SQL Server process."

https://learn.microsoft.com/en-US/troubleshoot/sql/tools/use-sqldumper-generate-dump-file#extended-dbcc-stackdump-functionality-introduced-in-sql-server-2019

Starting with SQL Server 2019 CU2, the DBCC STACKDUMP command was extended to support generating dumps of different types: mini, filtered, full dumps. 
This command eliminates the need for using trace flags.

***********************************************************/

